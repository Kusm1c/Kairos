"""Generates src/mod/PodFields.inc from the Geode bindings.

POD    plain value, safe to copy as bytes
REF    pointer to a level object (lives as long as the layer)
BOX    std container, copied by assignment (whitelisted)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIND = os.path.join(ROOT, "build", "bindings", "bindings", "Geode", "binding")
ENUMS = os.path.join(os.path.dirname(ROOT), "Kairos-bindings", "bindings", "include", "Geode", "Enums.hpp")
OUT = os.path.join(ROOT, "src", "kairos", "PodFields.inc")

SCALARS = {
    "bool", "char", "signed char", "unsigned char", "short", "unsigned short", "int", "unsigned int",
    "unsigned", "long", "unsigned long", "long long", "unsigned long long", "float", "double",
    "int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t", "int64_t", "uint64_t",
    "cocos2d::CCPoint", "cocos2d::CCSize", "cocos2d::CCRect", "cocos2d::ccColor3B", "cocos2d::ccColor4B",
    "cocos2d::ccColor4F", "GJPointDouble", "geode::SeedValueRSV", "geode::SeedValueVRS", "geode::SeedValueRS",
    "geode::SeedValueSR", "geode::SeedValueVSR", "geode::SeedValueSRV", "geode::SeedValueSVR",
}
LEVEL_OBJECTS = {"GameObject*", "DashRingObject*", "RingObject*", "EffectGameObject*", "EnhancedGameObject*",
                 "TeleportPortalObject*"}
PLAYER_BOXES = {"m_rotateObjectsRelated", "m_potentialSlopeMap", "m_ringRelatedSet", "m_touchedRings",
                "m_playerFollowFloats", "m_jumpPadRelated", "m_holdingButtons"}

MEMBER = re.compile(r"^\s*(?P<type>[A-Za-z_][\w:<>,\s\*&]*?)\s*(?P<name>m_\w+)\s*(\{\})?\s*;\s*$")


def enums():
    with open(ENUMS, encoding="utf-8") as fh:
        return set(re.findall(r"^\s*enum\s+(?:class\s+)?(\w+)", fh.read(), re.M))


def members(cls):
    with open(os.path.join(BIND, cls + ".hpp"), encoding="utf-8") as fh:
        lines = fh.readlines()
    out = []
    for ln in lines:
        if "(" in ln or ln.strip().startswith(("/", "*", "#")):
            continue
        m = MEMBER.match(ln)
        if m:
            t = re.sub(r"\s+", " ", m.group("type")).replace(" *", "*").strip()
            out.append((t, m.group("name")))
    return out


def classify(t, en):
    if t in SCALARS or t in en:
        return "POD"
    if t in LEVEL_OBJECTS:
        return "REF"
    return None


def main():
    en = enums()
    lines = ["// Generated by tools/gen_podfields.py", ""]

    def emit(macro, items):
        lines.append("#ifdef " + macro)
        lines.extend("%s(%s)" % (macro, n) for n in items)
        lines.append("#endif")
        lines.append("")

    seen = set()
    player_pod, player_ref, player_box = [], [], []
    for cls in ("GameObject", "PlayerObject"):
        for t, n in members(cls):
            if n in seen:
                continue
            seen.add(n)
            k = classify(t, en)
            if cls == "PlayerObject" and n in PLAYER_BOXES:
                player_box.append(n)
            elif k == "POD":
                player_pod.append(n)
            elif k == "REF" and cls == "PlayerObject":
                player_ref.append(n)
    state_pod, state_ref = [], []
    for t, n in members("GJGameState"):
        k = classify(t, en)
        (state_pod if k == "POD" else state_ref if k == "REF" else []).append(n)
    layer_pod, seen = [], set()
    for cls in ("GJBaseGameLayer", "PlayLayer"):
        for t, n in members(cls):
            if n not in seen and classify(t, en) == "POD":
                seen.add(n)
                layer_pod.append(n)

    emit("PLAYER_POD", player_pod)
    emit("PLAYER_REF", player_ref)
    emit("PLAYER_BOX", player_box)
    emit("STATE_POD", state_pod)
    emit("STATE_REF", state_ref)
    emit("LAYER_POD", layer_pod)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("player pod %d ref %d box %d / state pod %d ref %d / layer pod %d" %
          (len(player_pod), len(player_ref), len(player_box), len(state_pod), len(state_ref), len(layer_pod)))


if __name__ == "__main__":
    main()
